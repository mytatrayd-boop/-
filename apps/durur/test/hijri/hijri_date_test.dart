import 'package:durur/src/hijri/hijri_date.dart';
import 'package:flutter_test/flutter_test.dart';

// المصدر المرجعي لكل التواريخ في هذا الملف (SPEC الميزة 2، المعيار 3):
// تقويم أم القرى كما تنشره تطبيقات مستقلة منشورة، وقد طابقت كلها يوماً بيوم:
//   1) Java SE 21: java.time.chrono.HijrahChronology (المعرّف Hijrah-umalqura،
//      النوع islamic-umalqura، ملف hijrah-config-Hijrah-umalqura_islamic-umalqura).
//   2) ICU 77 (Intl في Node 22) بالتقويم islamic-umalqura.
//   3) جدول R. H. van Gent لأم القرى كما في حزمة بايثون hijridate 2.5.0
//      (ummalqura.py, MONTH_STARTS).
// لم يُتح الوصول إلى الموقع الرسمي ummulqura.org.sa من بيئة البناء.
// تنبيه: من 2029-08-11 يختلف (1)+(2) عن (3) ومكتبة hijri في بعض بدايات
// الأشهر بيوم؛ لذلك كل التواريخ هنا مما اتفقت عليه المصادر الثلاثة،
// والخلاف مسجّل للمراجع في STATUS.md.

void main() {
  HijriDate h(DateTime d) => HijriDate.fromGregorian(d);

  group('المعيار 3: تواريخ مرجعية لأم القرى 2025–2035', () {
    // (سنة, شهر, يوم) ميلادي ← (سنة, شهر, يوم) هجري.
    const references = <(int, int, int, int, int, int)>[
      (2025, 1, 1, 1446, 7, 1), // 1 رجب 1446
      (2025, 3, 1, 1446, 9, 1), // 1 رمضان 1446
      (2025, 3, 30, 1446, 10, 1), // 1 شوال 1446
      (2025, 6, 25, 1446, 12, 29), // آخر يوم في 1446
      (2025, 6, 26, 1447, 1, 1), // 1 محرم 1447
      (2025, 12, 31, 1447, 7, 11), // آخر يوم في 2025
      (2026, 1, 1, 1447, 7, 12), // أول يوم في 2026
      (2026, 2, 18, 1447, 9, 1), // 1 رمضان 1447
      (2026, 3, 20, 1447, 10, 1), // 1 شوال 1447
      (2026, 6, 15, 1447, 12, 29), // آخر يوم في 1447
      (2026, 6, 16, 1448, 1, 1), // 1 محرم 1448
      (2026, 10, 2, 1448, 4, 21), // 21 ربيع الآخر 1448
      (2027, 2, 8, 1448, 9, 1), // 1 رمضان 1448
      (2027, 6, 6, 1449, 1, 1), // 1 محرم 1449
      (2028, 1, 28, 1449, 9, 1), // 1 رمضان 1449
      (2028, 2, 29, 1449, 10, 4), // يوم كبيس ميلادي
      (2028, 5, 24, 1449, 12, 29), // آخر يوم في 1449
      (2028, 5, 25, 1450, 1, 1), // 1 محرم 1450
      (2029, 5, 14, 1451, 1, 1), // 1 محرم 1451
      (2030, 1, 5, 1451, 9, 1), // 1 رمضان 1451
      (2031, 4, 23, 1453, 1, 1), // 1 محرم 1453
      (2032, 2, 29, 1453, 11, 18), // يوم كبيس ميلادي
      (2032, 4, 11, 1454, 1, 1), // 1 محرم 1454
      (2032, 12, 4, 1454, 9, 1), // 1 رمضان 1454
      (2033, 4, 1, 1455, 1, 1), // 1 محرم 1455
      (2034, 11, 12, 1456, 9, 1), // 1 رمضان 1456
      (2035, 3, 11, 1457, 1, 1), // 1 محرم 1457
      (2035, 12, 1, 1457, 10, 1), // 1 شوال 1457
    ];

    test('العدد 20 على الأقل وموزّع على كل سنة من 2025 إلى 2035', () {
      expect(references.length, greaterThanOrEqualTo(20));
      final years = references.map((r) => r.$1).toSet();
      for (var y = 2025; y <= 2035; y++) {
        expect(years, contains(y), reason: 'السنة $y بلا تاريخ مرجعي');
      }
    });

    for (final (gy, gm, gd, hy, hm, hd) in references) {
      test('$gy-$gm-$gd ← $hy-$hm-$hd', () {
        expect(h(DateTime(gy, gm, gd)), HijriDate(hy, hm, hd));
      });
    }
  });

  group('حدود الأشهر', () {
    // بداية كل شهر من رجب 1446 إلى ذي الحجة 1450 (54 شهراً)،
    // من المصادر نفسها أعلاه (متفقة كلها في هذا المدى).
    const monthStarts = <(int, int, int, int, int)>[
    (2025, 1, 1, 1446, 7),
    (2025, 1, 31, 1446, 8),
    (2025, 3, 1, 1446, 9),
    (2025, 3, 30, 1446, 10),
    (2025, 4, 29, 1446, 11),
    (2025, 5, 28, 1446, 12),
    (2025, 6, 26, 1447, 1),
    (2025, 7, 26, 1447, 2),
    (2025, 8, 24, 1447, 3),
    (2025, 9, 23, 1447, 4),
    (2025, 10, 23, 1447, 5),
    (2025, 11, 22, 1447, 6),
    (2025, 12, 21, 1447, 7),
    (2026, 1, 20, 1447, 8),
    (2026, 2, 18, 1447, 9),
    (2026, 3, 20, 1447, 10),
    (2026, 4, 18, 1447, 11),
    (2026, 5, 18, 1447, 12),
    (2026, 6, 16, 1448, 1),
    (2026, 7, 15, 1448, 2),
    (2026, 8, 14, 1448, 3),
    (2026, 9, 12, 1448, 4),
    (2026, 10, 12, 1448, 5),
    (2026, 11, 11, 1448, 6),
    (2026, 12, 10, 1448, 7),
    (2027, 1, 9, 1448, 8),
    (2027, 2, 8, 1448, 9),
    (2027, 3, 9, 1448, 10),
    (2027, 4, 8, 1448, 11),
    (2027, 5, 7, 1448, 12),
    (2027, 6, 6, 1449, 1),
    (2027, 7, 5, 1449, 2),
    (2027, 8, 3, 1449, 3),
    (2027, 9, 2, 1449, 4),
    (2027, 10, 1, 1449, 5),
    (2027, 10, 31, 1449, 6),
    (2027, 11, 29, 1449, 7),
    (2027, 12, 29, 1449, 8),
    (2028, 1, 28, 1449, 9),
    (2028, 2, 26, 1449, 10),
    (2028, 3, 27, 1449, 11),
    (2028, 4, 26, 1449, 12),
    (2028, 5, 25, 1450, 1),
    (2028, 6, 24, 1450, 2),
    (2028, 7, 23, 1450, 3),
    (2028, 8, 22, 1450, 4),
    (2028, 9, 20, 1450, 5),
    (2028, 10, 19, 1450, 6),
    (2028, 11, 18, 1450, 7),
    (2028, 12, 17, 1450, 8),
    (2029, 1, 16, 1450, 9),
    (2029, 2, 14, 1450, 10),
    (2029, 3, 16, 1450, 11),
    (2029, 4, 15, 1450, 12),
    ];

    for (final (gy, gm, gd, hy, hm) in monthStarts) {
      test('1 من الشهر $hm/$hy يوافق $gy-$gm-$gd، وقبله آخر الشهر السابق',
          () {
        final start = DateTime(gy, gm, gd);
        expect(h(start), HijriDate(hy, hm, 1));

        final prev = h(DateTime(gy, gm, gd - 1));
        expect(prev.month, hm == 1 ? 12 : hm - 1);
        expect(prev.year, hm == 1 ? hy - 1 : hy);
        expect(prev.day, anyOf(29, 30));
      });
    }
  });

  group('حدود السنوات', () {
    test('ليلة رأس السنة الهجرية 1448: 29 ذو الحجة 1447 ثم 1 محرم 1448', () {
      expect(h(DateTime(2026, 6, 15)), const HijriDate(1447, 12, 29));
      expect(h(DateTime(2026, 6, 16)), const HijriDate(1448, 1, 1));
    });

    test('رأس السنة الميلادية 2027 لا يقطع التسلسل الهجري', () {
      final dec31 = h(DateTime(2026, 12, 31));
      final jan1 = h(DateTime(2027, 1, 1));
      expect(jan1.year, dec31.year);
      expect(jan1.month, dec31.month);
      expect(jan1.day, dec31.day + 1);
    });

    test('تسلسل سليم لكل يوم من 2025 إلى 2035', () {
      // كل يوم إما اليوم التالي في الشهر نفسه، أو 1 من الشهر التالي بعد
      // يوم 29 أو 30، وطول السنة الهجرية 354 أو 355 يوماً.
      var prev = h(DateTime(2025, 1, 1));
      var yearLength = 0;
      final yearLengths = <int, int>{};
      for (var d = DateTime.utc(2025, 1, 2);
          !d.isAfter(DateTime.utc(2035, 12, 31));
          d = d.add(const Duration(days: 1))) {
        final cur = h(d);
        yearLength++;
        if (cur.day == 1) {
          expect(prev.day, anyOf(29, 30), reason: 'قبل $d');
          if (prev.month == 12) {
            expect((cur.year, cur.month), (prev.year + 1, 1), reason: '$d');
            yearLengths[prev.year] = yearLength - 1; // بلا 1 محرم الجديد
            yearLength = 1;
          } else {
            expect((cur.year, cur.month), (prev.year, prev.month + 1),
                reason: '$d');
          }
        } else {
          expect((cur.year, cur.month, cur.day),
              (prev.year, prev.month, prev.day + 1),
              reason: '$d');
        }
        prev = cur;
      }
      // السنوات الكاملة داخل المدى: 1447..1456.
      for (var y = 1447; y <= 1456; y++) {
        expect(yearLengths[y], anyOf(354, 355), reason: 'طول السنة $y');
      }
    });
  });

  test('يتجاهل الوقت داخل اليوم', () {
    expect(h(DateTime(2026, 2, 18, 23, 59)), const HijriDate(1447, 9, 1));
    expect(h(DateTime(2026, 2, 18)), const HijriDate(1447, 9, 1));
    expect(h(DateTime.utc(2026, 2, 18)), const HijriDate(1447, 9, 1));
  });
}
